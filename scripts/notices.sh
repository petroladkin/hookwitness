#!/bin/bash
# Writes THIRD-PARTY-NOTICES.md to stdout: every module compiled into the
# hookwitness binary, its version, its license, and the full text of every
# license and notice file at the module's root (BSD and MIT require the text
# to travel with binary distributions).
#
# Fails when a module's license is not one of the permissive licenses this
# project accepts, so a copyleft dependency cannot slip in unnoticed.
#
# Usage: scripts/notices.sh > THIRD-PARTY-NOTICES.md   (or: make notices)
set -euo pipefail

classify() {
  local f=$1
  if grep -qE 'GNU (Affero |Lesser )?General Public License|Mozilla Public License' "$f"; then
    echo "REFUSED"
  elif grep -q 'Apache License' "$f" && grep -q 'Version 2.0' "$f"; then
    echo "Apache-2.0"
  elif grep -q 'Permission is hereby granted, free of charge' "$f"; then
    echo "MIT"
  elif grep -q 'Redistribution and use' "$f"; then
    if grep -q 'Neither the name' "$f"; then echo "BSD-3-Clause"; else echo "BSD-2-Clause"; fi
  elif grep -q 'Permission to use, copy, modify, and/or distribute' "$f"; then
    echo "ISC"
  else
    echo "UNKNOWN"
  fi
}

modules=$(go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}}{{end}}{{end}}' ./cmd/hookwitness | LC_ALL=C sort -u)

cat <<'HEAD'
# Third-party notices

Hookwitness is licensed under the Apache License 2.0 (see LICENSE). The
binary also contains the following modules, each under its own license,
reproduced in full below. This file is generated by `make notices`; a test
fails when it falls out of step with the modules actually compiled in.
HEAD

for m in $modules; do
  dir=$(go list -m -f '{{.Dir}}' "$m")
  ver=$(go list -m -f '{{.Version}}' "$m")
  main=""
  for cand in LICENSE LICENSE.md LICENSE.txt LICENCE COPYING; do
    if [ -f "$dir/$cand" ]; then main="$dir/$cand"; break; fi
  done
  if [ -z "$main" ]; then
    echo "notices: $m has no LICENSE file at its root" >&2
    exit 1
  fi
  spdx=$(classify "$main")
  case "$spdx" in
    REFUSED|UNKNOWN)
      echo "notices: $m: license is $spdx ($main); only permissive licenses are accepted" >&2
      exit 1
      ;;
  esac
  printf '\n## %s\n\nVersion %s, license %s.\n' "$m" "$ver" "$spdx"
  for f in $(cd "$dir" && ls | LC_ALL=C sort | grep -E '^(LICEN[CS]E|COPYING|NOTICE|PATENTS)' || true); do
    printf '\n### %s\n\n`````text\n' "$f"
    cat "$dir/$f"
    case "$(tail -c1 "$dir/$f")" in "") ;; *) echo ;; esac
    printf '`````\n'
  done
done
