#!/bin/bash
# Writes THIRD-PARTY-NOTICES.md to stdout: every module compiled into the
# hookwitness binary, its version, its license, and the full text of every
# license and notice file at the module's root (BSD and MIT require the text
# to travel with binary distributions); then every asset bundled under
# internal/web/static/vendor/<name>/ and internal/report/fonts/<name>/ (a
# LICENSE and a SOURCE file beside it); then third-party test material, the
# testdata/<name>/ directories that hold a SOURCE file.
#
# Fails when a module's license is not one of the permissive licenses this
# project accepts, so a copyleft dependency cannot slip in unnoticed.
#
# Usage: scripts/notices.sh > THIRD-PARTY-NOTICES.md   (or: make notices)
set -euo pipefail

classify() {
  local f=$1
  if grep -qE 'GNU (Affero |Lesser )?General Public License|Mozilla Public License' "$f"; then
    echo "REFUSED"
  elif grep -qE 'Zero-Clause BSD|BSD Zero Clause' "$f"; then
    echo "0BSD"
  elif grep -q 'SIL Open Font License' "$f" && grep -q 'Version 1.1' "$f"; then
    echo "OFL-1.1"
  elif grep -q 'Apache License' "$f" && grep -q 'Version 2.0' "$f"; then
    echo "Apache-2.0"
  elif grep -q 'Permission is hereby granted, free of charge' "$f"; then
    echo "MIT"
  elif grep -q 'Redistribution and use' "$f"; then
    if grep -q 'Neither the name' "$f"; then echo "BSD-3-Clause"; else echo "BSD-2-Clause"; fi
  elif grep -q 'Permission to use, copy, modify, and/or distribute' "$f"; then
    echo "ISC"
  else
    echo "UNKNOWN"
  fi
}

# The module set differs per target OS, so the notices cover the union of the
# platforms hookwitness is built for; keep this list in step with
# internal/repoguard/notices_test.go.
PLATFORMS="linux/amd64 linux/arm64 darwin/amd64 darwin/arm64 windows/amd64 freebsd/amd64"
modules=$(for p in $PLATFORMS; do
  GOOS=${p%/*} GOARCH=${p#*/} go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}}{{end}}{{end}}' ./cmd/hookwitness
done | LC_ALL=C sort -u)

cat <<'HEAD'
# Third-party notices

Hookwitness is licensed under the Apache License 2.0 (see LICENSE). The
binary also contains the following modules, each under its own license,
reproduced in full below. This file is generated by `make notices`; a test
fails when it falls out of step with the modules actually compiled in.
HEAD

for m in $modules; do
  dir=$(go list -m -f '{{.Dir}}' "$m")
  ver=$(go list -m -f '{{.Version}}' "$m")
  main=""
  for cand in LICENSE LICENSE.md LICENSE.txt LICENCE COPYING; do
    if [ -f "$dir/$cand" ]; then main="$dir/$cand"; break; fi
  done
  if [ -z "$main" ]; then
    echo "notices: $m has no LICENSE file at its root" >&2
    exit 1
  fi
  spdx=$(classify "$main")
  case "$spdx" in
    REFUSED|UNKNOWN)
      echo "notices: $m: license is $spdx ($main); only permissive licenses are accepted" >&2
      exit 1
      ;;
  esac
  printf '\n## %s\n\nVersion %s, license %s.\n' "$m" "$ver" "$spdx"
  for f in $(cd "$dir" && ls | LC_ALL=C sort | grep -E '^(LICEN[CS]E|COPYING|NOTICE|PATENTS)' || true); do
    printf '\n### %s\n\n`````text\n' "$f"
    cat "$dir/$f"
    case "$(tail -c1 "$dir/$f")" in "") ;; *) echo ;; esac
    printf '`````\n'
  done
done

cat <<'ASSETS'

# Bundled assets

The web UI and the PDF reports embed these files in the binary. In the
source tree each directory holds the files, their LICENSE and a SOURCE note
(package, version, origin).
ASSETS

notice_dir() {
  dir=$1
  if [ ! -f "$dir/LICENSE" ] || [ ! -f "$dir/SOURCE" ]; then
    echo "notices: $dir needs a LICENSE and a SOURCE file" >&2
    exit 1
  fi
  spdx=$(classify "$dir/LICENSE")
  case "$spdx" in
    REFUSED|UNKNOWN)
      echo "notices: $dir: license is $spdx; only permissive licenses are accepted" >&2
      exit 1
      ;;
  esac
  printf '\n## %s\n\n%s, license %s.\n\n`````text\n' "$dir" "$(head -n1 "$dir/SOURCE")" "$spdx"
  cat "$dir/LICENSE"
  case "$(tail -c1 "$dir/LICENSE")" in "") ;; *) echo ;; esac
  printf '`````\n'
}

for dir in $(ls -d internal/web/static/vendor/*/ internal/report/fonts/*/ | LC_ALL=C sort); do
  notice_dir "${dir%/}"
done

cat <<'TESTDATA'

# Third-party test material

Not built into the binary; present in the source tree for the tests. Each
directory under testdata/ that holds third-party files has their LICENSE
and a SOURCE note.
TESTDATA

for src in $(ls testdata/*/SOURCE | LC_ALL=C sort); do
  notice_dir "$(dirname "$src")"
done
